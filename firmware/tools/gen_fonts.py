"""Generate components/rg/rg_fonts.c and include/rg_fonts.h: the OLED's bitmap fonts.

Source: Rubik Bold 1.100 (SIL OFL 1.1; license: components/rg/fonts/LICENSE-Rubik.txt),
rendered without anti-aliasing exactly as the 1-bit SSD1306 shows it. Each font holds only the
glyphs the UI uses. Rerun after changing FONTS or the font file:

    uv run --no-project --with pillow -- python firmware/tools/gen_fonts.py \
        /path/to/Rubik-Bold.ttf firmware/components/rg
    clang-format --style=file:firmware/.clang-format -i firmware/components/rg/include/rg_fonts.h

rg_fonts.c is excluded from the clang-format check (CI), like rg_font5x7.c.
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

TURKISH = "ÇĞİÖŞÜ"
ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
# name, sample glyph, its height in px, glyph set
FONTS = [
    ("count", "0", 18, "#0123456789-"),                              # message count
    ("mid", "0", 14, "0123456789:-"),                               # recording countdown
    ("big", "H", 13, " !-.:?0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ" + TURKISH),  # action lines
    ("head", "H", 11, " !-.:?0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ" + TURKISH), # error / Wi-Fi titles
    ("small", "H", 9, ASCII + TURKISH + "çğıöşü"),                  # captions, hints, Wi-Fi details
]


def pick(path, sample, height):
    size = 6
    while True:
        b = ImageFont.truetype(path, size + 1).getbbox(sample, anchor="ls")
        if b[3] - b[1] > height:
            return size
        size += 1


def glyph_columns(font, ch, ascent, height):
    adv = round(font.getlength(ch))
    pad = 6
    im = Image.new("1", (adv + 2 * pad, height), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((pad, ascent), ch, font=font, fill=1, anchor="ls")
    cols = []
    for x in range(im.width):
        mask = 0
        for y in range(height):
            if im.getpixel((x, y)):
                mask |= 1 << y
        cols.append(mask)
    ink = [i for i, m in enumerate(cols) if m]
    if not ink:
        return adv, 0, []
    return adv, ink[0] - pad, cols[ink[0]:ink[-1] + 1]


def build(path, name, sample, px, chars):
    size = pick(path, sample, px)
    font = ImageFont.truetype(path, size)
    ascent = max(-font.getbbox(c, anchor="ls")[1] for c in chars if c != " ")
    descent = max(font.getbbox(c, anchor="ls")[3] for c in chars if c != " ")
    height = ascent + descent
    assert height <= 32, (name, height)
    glyphs, cols = [], []
    for ch in sorted(chars, key=ord):
        adv, x0, c = glyph_columns(font, ch, ascent, height)
        glyphs.append((ord(ch), adv, x0, len(c), len(cols), ch))
        cols.extend(c)
    return dict(name=name, size=size, px=px, sample=sample, ascent=ascent, height=height, glyphs=glyphs, cols=cols)


def emit(fonts, outdir):
    c = ["/* Generated by firmware/tools/gen_fonts.py from Rubik Bold. Do not edit.",
         " * License (SIL OFL 1.1): components/rg/fonts/LICENSE-Rubik.txt */",
         '#include "rg_fonts.h"', ""]
    for f in fonts:
        n = f["name"]
        c.append(f"/* {n}: {f['size']} px ('{f['sample']}' = {f['px']} px), {f['height']} px box, "
                 f"{f['ascent']} rows above the baseline. One uint32_t per column, bit n = row n. */")
        c.append(f"static const uint32_t {n}_cols[] = {{")
        for code, adv, x0, w, off, ch in f["glyphs"]:
            if w:
                c.append("    " + ", ".join(f"0x{v:08X}" for v in f["cols"][off:off + w]) + f", /* U+{code:04X} */")
        c.append("};")
        c.append(f"static const rg_glyph_t {n}_glyphs[] = {{")
        for code, adv, x0, w, off, ch in f["glyphs"]:
            c.append(f"    {{0x{code:04X}, {adv}, {x0}, {w}, {off}}}, /* U+{code:04X} */")
        c.append("};")
        c.append(f"const rg_font_t rg_font_{n} = {{{n}_glyphs, sizeof({n}_glyphs) / sizeof({n}_glyphs[0]), "
                 f"{n}_cols, {f['height']}, {f['ascent']}}};")
        c.append("")
    with open(os.path.join(outdir, "rg_fonts.c"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(c))

    h = ["#pragma once", "", "#include <stdint.h>", "",
         "/* Bitmap fonts generated by firmware/tools/gen_fonts.py (Rubik Bold). */", "",
         "typedef struct {",
         "    uint16_t cp;  /* Unicode code point (glyphs sorted ascending) */",
         "    uint8_t adv;  /* pen advance in px */",
         "    int8_t x0;    /* first ink column relative to the pen */",
         "    uint8_t w;    /* ink columns */",
         "    uint16_t off; /* index of the first column in cols */",
         "} rg_glyph_t;", "",
         "typedef struct {",
         "    const rg_glyph_t *glyphs;",
         "    uint16_t count;",
         "    const uint32_t *cols; /* one per pixel column, bit n = row n of the box */",
         "    uint8_t height;       /* box height in rows */",
         "    uint8_t ascent;       /* rows above the baseline */",
         "} rg_font_t;", ""]
    for f in fonts:
        chars = "".join(chr(g[0]) for g in f["glyphs"])
        desc = "printable ASCII + Turkish letters" if len(chars) > 90 else repr(chars.strip())[1:-1]
        h.append(f"extern const rg_font_t rg_font_{f['name']}; /* {f['px']} px '{f['sample']}': {desc} */")
    h.append("")
    with open(os.path.join(outdir, "include", "rg_fonts.h"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(h))


def main(ttf, outdir):
    fonts = [build(ttf, *spec) for spec in FONTS]
    emit(fonts, outdir)
    for f in fonts:
        print(f"{f['name']}: size {f['size']}, box {f['height']} (ascent {f['ascent']}), "
              f"{len(f['glyphs'])} glyphs, {len(f['cols'])} columns")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
